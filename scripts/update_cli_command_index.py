#!/usr/bin/env python3
"""Regenerate ``src/clm/cli/_command_index.py`` from the live command tree.

Usage:
    python scripts/update_cli_command_index.py           # rewrite the index
    python scripts/update_cli_command_index.py --check   # exit 1 if stale

The index lists every visible command path below ``clm``. The root group
uses it to suggest the right group on ``No such command 'X'`` without
importing the command modules (issue #1241). Run this after adding,
renaming, hiding or removing a command; ``tests/cli/test_command_hints.py``
fails while the index is stale. Needs every optional extra installed
(``uv sync --extra all``) so optional groups are included.
"""

from __future__ import annotations

import sys
from pathlib import Path

INDEX_PATH = Path(__file__).resolve().parents[1] / "src" / "clm" / "cli" / "_command_index.py"

HEADER = '''"""Static index of visible ``clm`` command paths (issue #1241).

GENERATED by ``python scripts/update_cli_command_index.py`` — do not edit
by hand. Read by :mod:`clm.cli._command_hints` to suggest the right group
on ``No such command 'X'`` without importing any command module.
"""

COMMAND_PATHS: tuple[tuple[str, ...], ...] = (
'''


def render(paths: list[tuple[str, ...]]) -> str:
    lines = [HEADER]
    for path in paths:
        inner = ", ".join(f'"{p}"' for p in path)
        if len(path) == 1:
            inner += ","
        lines.append(f"    ({inner}),\n")
    lines.append(")\n")
    return "".join(lines)


def main(argv: list[str]) -> int:
    from clm.cli._command_hints import walk_command_tree
    from clm.cli.main import cli

    text = render(walk_command_tree(cli))
    current = INDEX_PATH.read_text(encoding="utf-8") if INDEX_PATH.exists() else ""
    if "--check" in argv:
        if text != current:
            print(f"{INDEX_PATH} is stale; run python scripts/update_cli_command_index.py")
            return 1
        return 0
    if text != current:
        INDEX_PATH.write_text(text, encoding="utf-8", newline="\n")
        print(f"Updated {INDEX_PATH}")
    else:
        print(f"{INDEX_PATH} is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
